const classicCache = new Map<string, Glyph>();
// A few useful glyphs beyond ASCII, same column format.
const EXTRA: Record<string, number[]> = { '°': [0x00, 0x06, 0x09, 0x09, 0x06] };
// Common non-ASCII characters drawn with their closest ASCII glyph.
const ASCII_FALLBACK: Record<string, string> = { '×': 'x', '–': '-', '—': '-', '‘': "'", '’': "'", '“': '"', '”': '"', '″': '"', '′': "'", '…': '.' };

export const font5x7: Font = {
  name: '5x7',
  lineHeight: 8,
  glyph(ch: string): Glyph {
    let g = classicCache.get(ch);
    if (g) return g;
    let code = (ASCII_FALLBACK[ch] ?? ch).charCodeAt(0);
    if ((code < 0x20 || code > 0x7e) && !EXTRA[ch]) code = 0x3f; // '?'
    const bits = new Uint8Array(5 * 8);
    for (let col = 0; col < 5; col++) {
      const line = EXTRA[ch]?.[col] ?? FONT5X7[(code - 0x20) * 5 + col];
      for (let row = 0; row < 8; row++) if (line & (1 << row)) bits[row * 5 + col] = 1;
    }
    g = { w: 5, h: 8, xAdvance: 6, bits };
    classicCache.set(ch, g);
    return g;
  },
};

/**
 * Rasterise any font the browser has (e.g. '16px monospace', 'bold 24px Georgia') into 1-bit glyphs.
 * Good for trying out looks; for hardware, convert the font you settle on with Adafruit's fontconvert.
 */
export function browserFont(css: string, threshold = 110): Font {
  const cache = new Map<string, Glyph>();
  const size = Number(/(\d+(?:\.\d+)?)px/.exec(css)?.[1] ?? 16);
  const lineHeight = Math.ceil(size * 1.25);
  let ctx: OffscreenCanvasRenderingContext2D | CanvasRenderingContext2D | null = null;
  const getCtx = () => {
    if (ctx) return ctx;
    const canvas =
      typeof OffscreenCanvas !== 'undefined' ? new OffscreenCanvas(lineHeight * 2, lineHeight) : document.createElement('canvas');
    canvas.width = lineHeight * 2;
    canvas.height = lineHeight;
    ctx = canvas.getContext('2d', { willReadFrequently: true }) as typeof ctx;
    return ctx!;
  };
  return {
    name: css,
    lineHeight,
    glyph(ch: string): Glyph {
      let g = cache.get(ch);
      if (g) return g;
      const c = getCtx();
      c.font = css;
      const w = Math.max(1, Math.ceil(c.measureText(ch).width));
      if (c.canvas.width < w) c.canvas.width = w;
      c.clearRect(0, 0, c.canvas.width, c.canvas.height);
      c.font = css;
      c.textBaseline = 'top';
      c.fillStyle = '#000';
      c.fillText(ch, 0, Math.round((lineHeight - size) / 2));
      const img = c.getImageData(0, 0, w, lineHeight).data;
      const bits = new Uint8Array(w * lineHeight);
      for (let i = 0; i < bits.length; i++) bits[i] = img[i * 4 + 3] >= threshold ? 1 : 0;
      g = { w, h: lineHeight, xAdvance: w, bits };
      cache.set(ch, g);
      return g;
    },
  };
}
