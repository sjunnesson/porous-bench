// Fonts are 1-bit, like Adafruit GFX fonts on a microcontroller. The cursor is the top-left
// of the text line.

export interface Glyph {
  w: number;
  h: number;
  xAdvance: number;
  /** Row-major w*h, 1 = ink. */
  bits: Uint8Array;
}

export interface Font {
  name: string;
  lineHeight: number;
  glyph(ch: string): Glyph;
}

